export type I18nKey = keyof (typeof dict)["en"];

function lookup(lang: Lang, key: string): string {
  const d = dict[lang] as unknown as Record<string, string>;
  const en = dict.en as unknown as Record<string, string>;
  return d?.[key] ?? en[key] ?? key;
}

function fill(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.split(`{${k}}`).join(String(v)), s);
}

// Typed version for components.
export function t(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  return fill(lookup(lang, key), vars);
}

// Untyped version for the engine, which builds keys like `win.${role}.${tempo}`.
export function tx(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  return fill(lookup(lang, key), vars);
}

// 1300 -> "1.300" (pt-BR) / "1,300" (en)
export function fmtGold(lang: Lang, n: number): string {
  return Math.round(n).toLocaleString(lang === "pt-BR" ? "pt-BR" : "en-US");
}
